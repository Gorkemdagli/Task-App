@dataclass
class Session:
    thread_id: str | None = None
    started: datetime | None = None
    cwd: str | None = None
    parent_id: str | None = None
    agent_role: str | None = None
    task_records: set[tuple[datetime | None, str, int]] = field(default_factory=set)
    task_observation_count: int = 0
    missing_task_duration_count: int = 0
    spawn_calls: set[tuple[str, str, str]] = field(default_factory=set)
    unparsed_spawn_calls: set[str] = field(default_factory=set)
    composite_subagent_paths: set[str] = field(default_factory=set)
    composite_history_start_ordinal: int | None = None
    composite_token_records: set[tuple[datetime | None, int]] = field(default_factory=set)
    composite_token_observations: int = 0
    token_records: set[tuple[datetime | None, int]] = field(default_factory=set)
    category_records: set[tuple[datetime | None, int | None, int | None, int | None, int | None, int | None]] = field(default_factory=set)
    tokens: int | None = None
    category_tokens: dict[str, int | None] = field(default_factory=dict)
    token_decreases: int = 0
    token_timestamp_conflicts: int = 0
    untimed_token_snapshots: int = 0
    first_event: datetime | None = None
    last_event: datetime | None = None
    timestamps: set[datetime] = field(default_factory=set)
    malformed: int = 0
    missing_usage_value: int = 0
    metadata_values: dict[str, set[Any]] = field(default_factory=lambda: defaultdict(set))
    metadata_conflicts: set[str] = field(default_factory=set)
    physical_paths: set[str] = field(default_factory=set)

    def observe(self, when: datetime | None) -> None:
        if when is None:
            return
        self.timestamps.add(when)
        if self.first_event is None or when < self.first_event:
            self.first_event = when
        if self.last_event is None or when > self.last_event:
            self.last_event = when


def field_value(row: dict[str, Any], payload: dict[str, Any], key: str) -> Any:
    return payload.get(key, row.get(key))


def token_categories(usage: Any) -> tuple[int | None, int | None, int | None, int | None]:
    if not isinstance(usage, dict):
        usage = {}
    input_tokens = usage.get("input_tokens")
    cached_input_tokens = usage.get("cached_input_tokens")
    valid_input = isinstance(input_tokens, int) and not isinstance(input_tokens, bool) and input_tokens >= 0
    valid_cached = isinstance(cached_input_tokens, int) and not isinstance(cached_input_tokens, bool) and cached_input_tokens >= 0
    uncached = input_tokens - cached_input_tokens if valid_input and valid_cached and cached_input_tokens <= input_tokens else None
    return tuple(
        value if isinstance(value, int) and not isinstance(value, bool) and value >= 0 else None
        for value in (uncached, cached_input_tokens, usage.get("output_tokens"), usage.get("reasoning_output_tokens"))
    )


def add_metadata(session: Session, name: str, value: Any) -> None:
    if value is None and name != "parent_id":
        return
    if name == "cwd":
        value = os.path.normcase(os.path.normpath(str(value)))
    elif name == "parent_id":
        value = None if value is None or (isinstance(value, str) and not value.strip()) else str(value)
    elif name in {"thread_id", "agent_role"}:
        value = str(value)
    session.metadata_values[name].add(value)


def finalize_metadata(session: Session) -> None:
    for name, values in session.metadata_values.items():
        if len(values) > 1:
            session.metadata_conflicts.add(name)
        if len(values) == 1:
            value = next(iter(values))
        elif name == "started" and values:
            value = min(values)
        elif name == "parent_id":
            value = "__CONFLICTING_PARENT_METADATA__"
        else:
            value = None
        if name == "thread_id":
            session.thread_id = value
        elif name == "started":
            session.started = value
        elif name == "cwd":
            session.cwd = value
        elif name == "parent_id":
            session.parent_id = value
        elif name == "agent_role":
            session.agent_role = value


def finalize_metrics(session: Session) -> None:
    by_timestamp: dict[datetime, set[int]] = defaultdict(set)
    session.untimed_token_snapshots = 0
    for timestamp, total in session.token_records:
        if timestamp is None:
            session.untimed_token_snapshots += 1
        else:
            by_timestamp[timestamp].add(total)
    session.token_timestamp_conflicts = sum(len(totals) > 1 for totals in by_timestamp.values())
    session.token_decreases = 0
    previous: int | None = None
    for timestamp in sorted(by_timestamp):
        total = max(by_timestamp[timestamp])
        if previous is not None and total < previous:
            session.token_decreases += 1
        previous = total
    session.tokens = None if session.untimed_token_snapshots or not by_timestamp else max(by_timestamp[max(by_timestamp)])

    if any(timestamp is None for timestamp, *_ in session.category_records):
        session.category_tokens = dict.fromkeys(TOKEN_CATEGORIES)
        return
    category_by_timestamp: dict[datetime, set[tuple[int | None, int | None, int | None, int | None, int | None]]] = defaultdict(set)
    for timestamp, total, uncached, cached, output, reasoning in session.category_records:
        if timestamp is not None:
            category_by_timestamp[timestamp].add((total, uncached, cached, output, reasoning))
    session.category_tokens = dict.fromkeys(TOKEN_CATEGORIES)
    if not category_by_timestamp:
        return
    latest = category_by_timestamp[max(category_by_timestamp)]
    totals = [record[0] for record in latest if record[0] is not None]
    selected = [record for record in latest if record[0] == max(totals)] if totals else list(latest)
    for index, category in enumerate(TOKEN_CATEGORIES, start=1):
        values = {record[index] for record in selected}
        if len(values) == 1 and None not in values:
            session.category_tokens[category] = next(iter(values))


def read_session(path: Path, global_errors: dict[str, int]) -> Session:
    session = Session()
    try:
        session.physical_paths.add(str(path))
        metadata_rows: list[tuple[dict[str, Any], dict[str, Any], str]] = []
        with path.open("r", encoding="utf-8") as stream:
            for line in stream:
                try:
                    row = json.loads(line)
                except (json.JSONDecodeError, UnicodeDecodeError):
                    continue
                if not isinstance(row, dict) or row.get("type") != "session_meta":
                    continue
                payload = row.get("payload")
                if not isinstance(payload, dict):
                    payload = {}
                thread_id = field_value(row, payload, "id") or field_value(row, payload, "session_id")
                if thread_id:
                    metadata_rows.append((row, payload, str(thread_id)))
    except OSError:
        global_errors["unreadable_files"] += 1
        return session

    child_metadata = [
        entry for entry in metadata_rows
        if field_value(entry[0], entry[1], "thread_source") == "subagent"
    ]
    composite_child: tuple[dict[str, Any], dict[str, Any], str, int] | None = None
    metadata_ids = {entry[2] for entry in metadata_rows}
    if len(metadata_ids) == 2 and len(child_metadata) == 1:
        child_row, child_payload, child_id = child_metadata[0]
        parent_id = field_value(child_row, child_payload, "parent_thread_id")
        marker = child_payload.get("subagent_history_start_ordinal")
        parent_metadata = [
            entry for entry in metadata_rows
            if entry[2] == parent_id
            and field_value(entry[0], entry[1], "thread_source") == "user"
            and not field_value(entry[0], entry[1], "parent_thread_id")
        ]
        if (
            parent_id
            and child_id != str(parent_id)
            and field_value(child_row, child_payload, "session_id") == parent_id
            and field_value(child_row, child_payload, "forked_from_id") == parent_id
            and len(parent_metadata) == 1
            and isinstance(marker, int)
            and not isinstance(marker, bool)
            and marker >= 0
        ):
            composite_child = (child_row, child_payload, str(parent_id), marker)
            session.composite_subagent_paths.add(str(path))
            session.composite_history_start_ordinal = marker
            global_errors["composite_subagent_files"] += 1
            child_started = instant(field_value(child_row, child_payload, "timestamp")) or instant(child_row.get("timestamp"))
            add_metadata(session, "thread_id", child_id)
            add_metadata(session, "started", child_started)
            for key in ("cwd", "agent_role"):
                value = field_value(child_row, child_payload, key)
                if value is not None:
                    add_metadata(session, key, value)
            add_metadata(session, "parent_id", parent_id)
            session.observe(instant(child_row.get("timestamp")))

    try:
        stream = path.open("r", encoding="utf-8")
    except OSError:
        global_errors["unreadable_files"] += 1
        return session

    with stream:
        for line in stream:
            try:
                row = json.loads(line)
            except (json.JSONDecodeError, UnicodeDecodeError):
                session.malformed += 1
                global_errors["malformed_json_lines"] += 1
                continue
            if not isinstance(row, dict):
                session.malformed += 1
                global_errors["malformed_json_lines"] += 1
                continue

            payload = row.get("payload")
            if not isinstance(payload, dict):
                payload = {}
            event_time = instant(row.get("timestamp"))
            ordinal = row.get("ordinal")
            if composite_child is not None:
                if row.get("type") == "session_meta":
                    continue
                if not isinstance(ordinal, int) or isinstance(ordinal, bool) or ordinal < composite_child[3]:
                    continue
            session.observe(event_time)

            if row.get("type") == "session_meta" and composite_child is None:
                add_metadata(session, "thread_id", field_value(row, payload, "id") or field_value(row, payload, "session_id"))
                add_metadata(session, "started", instant(field_value(row, payload, "timestamp")) or event_time)
                for key in ("cwd", "agent_role"):
                    value = field_value(row, payload, key)
                    if value is not None:
                        add_metadata(session, key, value)
                parent_value = field_value(row, payload, "parent_thread_id")
                if "parent_thread_id" in payload or "parent_thread_id" in row:
                    add_metadata(session, "parent_id", parent_value)

            if row.get("type") == "token_usage_record":
                usage = payload.get("thread_token_usage")
                total = usage.get("total_tokens") if isinstance(usage, dict) else None
                category_values = token_categories(usage)
                valid_total = total if isinstance(total, int) and not isinstance(total, bool) and total >= 0 else None
                session.category_records.add((event_time, valid_total, *category_values))
                if isinstance(total, int) and not isinstance(total, bool) and total >= 0:
                    record = (event_time, total)
                    session.token_records.add(record)
                    if composite_child is not None:
                        session.composite_token_observations += 1
                        session.composite_token_records.add(record)
                else:
                    session.missing_usage_value += 1

            if row.get("type") == "task_complete" or payload.get("type") == "task_complete":
                duration = payload.get("duration_ms", row.get("duration_ms"))
                if isinstance(duration, int) and not isinstance(duration, bool) and duration >= 0:
                    identity = payload.get("turn_id") or row.get("turn_id") or ""
                    session.task_records.add((None if identity else event_time, str(identity), duration))
                    session.task_observation_count += 1
                else:
                    session.missing_task_duration_count += 1
            if row.get("type") == "response_item" and payload.get("type") == "function_call" and payload.get("name") == "spawn_agent":
                arguments = payload.get("arguments")
                if isinstance(arguments, str):
                    try:
                        arguments = json.loads(arguments)
                    except json.JSONDecodeError:
                        arguments = None
                call_id = payload.get("call_id") or payload.get("id") or f"{event_time}:{ordinal}"
                call_identity = str(call_id)
                if isinstance(arguments, dict):
                    role = arguments.get("agent_type")
                    task_name = arguments.get("task_name")
                    if isinstance(role, str) and role and isinstance(task_name, str) and task_name:
                        session.spawn_calls.add((call_identity, role, task_name))
                    else:
                        session.unparsed_spawn_calls.add(call_identity)
                else:
                    session.unparsed_spawn_calls.add(call_identity)
    finalize_metadata(session)
    finalize_metrics(session)
    return session


def normalized_path(value: str | None) -> str | None:
    if not value:
        return None
    try:
        return os.path.normcase(str(Path(value).resolve()))
    except OSError:
        return os.path.normcase(os.path.normpath(value))


def load_sessions(log_roots: list[Path]) -> tuple[dict[str, Session], dict[str, int]]:
    errors: dict[str, int] = defaultdict(int)
    candidates: dict[str, Session] = {}
    paths: list[Path] = []
    for root in log_roots:
        if not root.exists():
            continue
        try:
            paths.extend(path for path in root.rglob("rollout-*.jsonl") if path.is_file())
        except OSError:
            errors["scan_errors"] += 1

    for path in paths:
        candidate = read_session(path, errors)
        if not candidate.thread_id:
            errors["logs_missing_thread_id"] += 1
            if "thread_id" in candidate.metadata_conflicts:
                errors["conflicting_thread_ids"] += 1
            continue
        previous = candidates.get(candidate.thread_id)
        if previous is None:
            candidates[candidate.thread_id] = candidate
        else:
            errors["duplicate_thread_copies"] += 1
            previous.physical_paths.update(candidate.physical_paths)
            previous.timestamps.update(candidate.timestamps)
            if candidate.first_event is not None and (previous.first_event is None or candidate.first_event < previous.first_event):
                previous.first_event = candidate.first_event
            if candidate.last_event is not None and (previous.last_event is None or candidate.last_event > previous.last_event):
                previous.last_event = candidate.last_event
            previous.token_records.update(candidate.token_records)
            previous.category_records.update(candidate.category_records)
            previous.task_records.update(candidate.task_records)
            previous.task_observation_count += candidate.task_observation_count
            previous.missing_task_duration_count += candidate.missing_task_duration_count
            previous.spawn_calls.update(candidate.spawn_calls)
            previous.unparsed_spawn_calls.update(candidate.unparsed_spawn_calls)
            previous.composite_subagent_paths.update(candidate.composite_subagent_paths)
            if previous.composite_history_start_ordinal is None:
                previous.composite_history_start_ordinal = candidate.composite_history_start_ordinal
            previous.composite_token_records.update(candidate.composite_token_records)
            previous.composite_token_observations += candidate.composite_token_observations
            previous.malformed += candidate.malformed
            previous.missing_usage_value += candidate.missing_usage_value
            for name, values in candidate.metadata_values.items():
                previous.metadata_values[name].update(values)
    for session in candidates.values():
        finalize_metadata(session)
        finalize_metrics(session)
    errors["sessions_with_metadata_conflicts"] = sum(bool(session.metadata_conflicts) for session in candidates.values())
    return candidates, errors


def format_duration(milliseconds: int | None) -> str:
    if milliseconds is None:
        return "NOT AVAILABLE"
    seconds = milliseconds / 1000
    return f"{seconds:.3f}s ({milliseconds} ms)"


def session_duration(session: Session) -> int | None:
    if len(session.timestamps) < 2 or session.first_event is None or session.last_event is None:
        return None
    return max(0, int((session.last_event - session.first_event).total_seconds() * 1000))


def child_role(session: Session) -> str:
    if session.agent_role is None or "agent_role" in session.metadata_conflicts:
        return "unknown"
    return session.agent_role.strip().casefold() or "unknown"


def metric_text(values: list[int | None], average: bool = False) -> str:
    known = [value for value in values if value is not None]
    if len(known) != len(values):
        partial = f"{sum(known)}" if not average else (f"{sum(known) / len(known):.1f}" if known else "NOT AVAILABLE")
        label = "known partial" if not average else "known average"
        return f"NOT AVAILABLE ({label} {partial}; {len(known)}/{len(values)} threads)"
    if not known:
        return "NOT AVAILABLE"
    return f"{sum(known) / len(known):.1f}" if average else str(sum(known))


def duration_average(values: list[int | None]) -> str:
    known = [value for value in values if value is not None]
    if not known:
        return "NOT AVAILABLE"
    average = sum(known) / len(known) / 1000
    formatted = f"{average:.3f}s"
    return formatted if len(known) == len(values) else f"NOT AVAILABLE (known average {formatted}; {len(known)}/{len(values)} threads)"


def role_breakdown(children: list[Session]) -> list[str]:
    grouped: dict[str, list[Session]] = defaultdict(list)
    for child in children:
        grouped[child_role(child)].append(child)
    extra_roles = sorted(set(grouped) - set(CHILD_ROLES) - {"unknown"})
    roles = list(CHILD_ROLES) + ["unknown"] + extra_roles
    lines = [
        "Child-role breakdown (tokens are cumulative per-thread snapshots; duration is summed task_complete duration):",
        "  role source: session_meta.agent_role (payload or row); absent or conflicting values are unknown.",
        "  explicit additional role rows: " + (", ".join(extra_roles) if extra_roles else "none"),
        "  role | threads | uncached input avg/total | cached input avg/total | output avg/total | reasoning avg/total | avg duration",
    ]
    for role in roles:
        agents = grouped.get(role, [])
        categories = {
            category: [agent.category_tokens.get(category) for agent in agents]
            for category in TOKEN_CATEGORIES
        }
        durations = [
            sum(record[2] for record in agent.task_records)
            if agent.task_records and not agent.missing_task_duration_count else None
            for agent in agents
        ]
        pairs = [f"{metric_text(categories[category], True)}/{metric_text(categories[category])}" for category in TOKEN_CATEGORIES]
        duration = duration_average(durations)
        lines.append(f"  {role} | {len(agents)} | " + " | ".join(pairs) + f" | {duration}")
    return lines


def top_role(children: list[Session], getter: Any, denominator: str) -> str:
    totals: dict[str, int] = defaultdict(int)
    for child in children:
        value = getter(child)
        if value is not None:
            totals[child_role(child)] += value
    if not totals:
        return "NOT AVAILABLE (no known values)"
    total = sum(totals.values())
    leaders = sorted(role for role, value in totals.items() if value == max(totals.values()))
    leader_text = ", ".join(f"{role} ({totals[role]} tokens, {totals[role] / total:.1%})" for role in leaders)
    return f"{leader_text}; {denominator} known-value denominator {total} tokens"


def descendants(thread_id: str, children: dict[str, list[str]]) -> tuple[list[str], bool]:
    result: list[str] = []
    seen = {thread_id}
    stack = list(children.get(thread_id, []))
    cycle = False
    while stack:
        child_id = stack.pop()
        if child_id in seen:
            cycle = True
            continue
        seen.add(child_id)
        result.append(child_id)
        stack.extend(children.get(child_id, []))
    return result, cycle


def exclusion_subtrees(excluded_ids: list[str], threads: dict[str, Session], children: dict[str, list[str]]) -> tuple[dict[str, list[str] | None], set[str]]:
    details: dict[str, list[str] | None] = {}
    excluded_threads: set[str] = set()
    for session_id in excluded_ids:
        if session_id not in threads:
            details[session_id] = None
            continue
        child_ids, _ = descendants(session_id, children)
        subtree = [session_id, *child_ids]
        details[session_id] = subtree
        excluded_threads.update(subtree)
    return details, excluded_threads


def retry_metrics(threads: list[Session]) -> tuple[int, int, int, int, int]:
    repeated: dict[tuple[str, str], int] = defaultdict(int)
    parsed_calls = unparsed_calls = sessions_with_calls = 0
    for thread in threads:
        parsed_calls += len(thread.spawn_calls)
        unparsed_calls += len(thread.unparsed_spawn_calls)
        sessions_with_calls += bool(thread.spawn_calls or thread.unparsed_spawn_calls)
        for _, role, task_name in thread.spawn_calls:
            repeated[(role, task_name)] += 1
    loops = sum(count > 1 for count in repeated.values())
    extra_spawns = sum(count - 1 for count in repeated.values() if count > 1)
    return loops, extra_spawns, parsed_calls, unparsed_calls, sessions_with_calls


def print_reconstruction_audit(threads: dict[str, Session], errors: dict[str, int]) -> None:
    reconstructed = [session for session in threads.values() if session.composite_subagent_paths]
    parent_ids = {session.parent_id for session in reconstructed if session.parent_id}
    raw_snapshots = sum(session.composite_token_observations for session in reconstructed)
    deduped_snapshots = sum(len(session.composite_token_records) for session in reconstructed)
    print("Baseline reconstruction audit:")
    print(f"  explicit parent-linked subagent files: {errors.get('composite_subagent_files', 0)}")
    print(f"  distinct child IDs: {len(reconstructed)}; distinct parent IDs: {len(parent_ids)}")
    print(f"  excluded-file token snapshots: {raw_snapshots} raw; {deduped_snapshots} after per-child timestamp/value deduplication")
    print("  grouping fields: child thread_source=subagent; child id; parent_thread_id=session_id=forked_from_id=parent id; matching parent thread_source=user; rows before subagent_history_start_ordinal omitted")
    samples: dict[str, tuple[Session, str]] = {}
    for session in sorted(reconstructed, key=lambda item: (item.started or datetime.max.replace(tzinfo=timezone.utc), item.thread_id or "")):
        date = session.started.date().isoformat() if session.started else "NOT AVAILABLE"
        if date not in samples and session.composite_subagent_paths:
            samples[date] = (session, sorted(session.composite_subagent_paths)[0])
    for date, (session, path) in list(samples.items())[:5]:
        print(f"  sample {date}: {path}; child={session.thread_id}; parent={session.parent_id}; role={session.agent_role or 'NOT AVAILABLE'}; subagent_history_start_ordinal={session.composite_history_start_ordinal}")


def render_session(root: Session, threads: list[Session], child_ids: list[str], cycle: bool) -> tuple[str, int, int]:
    thread_count = len(threads)
    known_tokens = [thread.tokens for thread in threads if thread.tokens is not None]
    if len(known_tokens) == thread_count:
        token_text = str(sum(known_tokens))
    else:
        partial = sum(known_tokens)
        token_text = f"NOT AVAILABLE (known partial {partial}; {len(known_tokens)}/{thread_count} threads)"
    retry_loops, repeat_spawns, spawn_calls, unparsed_spawns, sessions_with_spawns = retry_metrics(threads)

    lines = [
        f"Session {root.thread_id}",
        f"  started: {root.started.isoformat() if root.started else 'NOT AVAILABLE'}",
        f"  observed wall span: {format_duration(session_duration(root))} (first-to-last log timestamp; may include idle time)",
        f"  total tokens (root + linked descendants): {token_text}",
        f"  linked child sessions: {len(child_ids)} (spawned sessions represented in logs; attempted calls are NOT AVAILABLE)",
        f"  physical log copies merged for root: {len(root.physical_paths)}",
        f"  retry loops: {retry_loops} (exact repeated agent_type + task_name pairs across the root and linked descendants; {repeat_spawns} repeat spawn(s) from {spawn_calls} parseable calls in {sessions_with_spawns} thread(s); {unparsed_spawns} unparsed spawn call(s))",
        f"  malformed JSON lines: {sum(thread.malformed for thread in threads)}",
    ]

    by_role: dict[str, list[Session]] = defaultdict(list)
    child_by_id = {thread.thread_id: thread for thread in threads[1:]}
    for child_id in child_ids:
        child = child_by_id.get(child_id)
        if child is not None:
            by_role[child.agent_role or "NOT AVAILABLE"].append(child)
    if not by_role:
        lines.append("  per-agent spawns: none linked")
    else:
        lines.append("  per-agent spawns:")
        for role, agents in sorted(by_role.items()):
            durations = [sum(record[2] for record in agent.task_records) if agent.task_records and not agent.missing_task_duration_count else None for agent in agents]
            known = [duration for duration in durations if duration is not None]
            if len(known) == len(agents):
                duration_text = format_duration(sum(known))
            else:
                duration_text = f"NOT AVAILABLE (known {len(known)}/{len(agents)}; {format_duration(sum(known)) if known else 'no known duration'})"
            lines.append(f"    {role}: linked spawn count {len(agents)}; summed task duration {duration_text}")
            for agent in agents:
                duration = sum(record[2] for record in agent.task_records) if agent.task_records and not agent.missing_task_duration_count else None
                lines.append(f"      {agent.thread_id}: {format_duration(duration)}; physical log copies merged {len(agent.physical_paths)}")
    if cycle:
        lines.append("  child graph: cycle detected; repeated links counted once")
    missing_usage = sum(thread.missing_usage_value for thread in threads)
    if missing_usage:
        lines.append(f"  malformed or missing token usage values: {missing_usage}")
    metadata_conflicts = sorted({name for thread in threads for name in thread.metadata_conflicts})
    if metadata_conflicts:
        lines.append(f"  conflicting metadata fields: {', '.join(metadata_conflicts)} (ambiguous cwd excluded; earliest conflicting start used; ambiguous parent link not followed)")
    token_decreases = sum(thread.token_decreases for thread in threads)
    if token_decreases:
        lines.append(f"  token anomaly: cumulative total decreased across {token_decreases} chronological snapshot transition(s)")
    token_ties = sum(thread.token_timestamp_conflicts for thread in threads)
    if token_ties:
        lines.append(f"  token anomaly: {token_ties} timestamp tie(s) had conflicting totals; greater cumulative total selected")
    untimed_tokens = sum(thread.untimed_token_snapshots for thread in threads)
    if untimed_tokens:
        lines.append(f"  token totals unavailable for {untimed_tokens} valid snapshot(s) without timestamps")
    duplicate_task_records = sum(thread.task_observation_count - len(thread.task_records) for thread in threads)
    if duplicate_task_records:
        lines.append(f"  duplicate task_complete observations merged: {duplicate_task_records}")
    return "\n".join(lines), len(known_tokens), thread_count


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", default=str(Path.cwd()), help="root-session cwd filter (default: current directory)")
    parser.add_argument("--logs-dir", action="append", help="scan this log tree instead of the default current and archived trees; repeatable")
    parser.add_argument("--before", type=cutoff, help="include roots strictly before this timezone-aware ISO 8601 instant")
    parser.add_argument("--after", type=cutoff, help="include roots strictly after this timezone-aware ISO 8601 instant")
    parser.add_argument("--after-started", type=cutoff, help="include roots whose session_meta start is strictly after this instant")
    parser.add_argument("--exclude-session", action="append", type=session_identifier, default=[], metavar="ID", help="exclude this session and its descendants; repeatable")
    parser.add_argument("--exclude-session-reason", action="append", type=exclusion_reason, default=[], metavar="ID=REASON", help="record a reason for an excluded session; repeatable")
    parser.add_argument("--rtk-gain", action="store_true", help="capture one timestamped global `rtk gain` snapshot as supplementary data")
    args = parser.parse_args()
    try:
        after_started = resolve_after(args.after, args.after_started)
    except argparse.ArgumentTypeError as error:
        parser.error(str(error))
    exclusion_ids = list(dict.fromkeys(args.exclude_session))
    exclusion_reasons = dict(args.exclude_session_reason)
    if set(exclusion_reasons) - set(exclusion_ids):
        parser.error("--exclude-session-reason IDs must also appear in --exclude-session")
    print_historical_baseline_preamble(args.before)

    roots = [Path(value).expanduser() for value in args.logs_dir] if args.logs_dir else [
        Path.home() / ".codex" / "sessions",
        Path.home() / ".codex" / "archived_sessions",
    ]
    threads, errors = load_sessions(roots)
    print_reconstruction_audit(threads, errors)
    workspace = normalized_path(args.workspace)
    children: dict[str, list[str]] = defaultdict(list)
    for thread in threads.values():
        if thread.parent_id and thread.parent_id in threads:
            children[thread.parent_id].append(thread.thread_id or "")

    exclusion_details, excluded_threads = exclusion_subtrees(exclusion_ids, threads, children)
    all_roots = [thread for thread in threads.values() if not thread.parent_id]
    all_workspace_roots = [thread for thread in all_roots if normalized_path(thread.cwd) == workspace]
    excluded_workspace_roots = [thread for thread in all_workspace_roots if thread.thread_id in excluded_threads]
    roots_without_cwd = sum(thread.cwd is None for thread in all_roots)
    roots_outside_workspace = len(all_roots) - roots_without_cwd - len(all_workspace_roots)
    missing_start = 0
    selected: list[Session] = []
    selected_excluded_roots: list[Session] = []
    for thread in all_workspace_roots:
        excluded_root = thread.thread_id in excluded_threads
        if (args.before or after_started) and thread.started is None:
            if not excluded_root:
                missing_start += 1
            continue
        if not matches_started(thread.started, args.before, after_started):
            continue
        (selected_excluded_roots if excluded_root else selected).append(thread)
    selected.sort(key=lambda thread: (thread.started or datetime.min.replace(tzinfo=timezone.utc), thread.thread_id or ""))

    print(f"Workspace: {args.workspace}")
    after_label = f"strictly after-started {after_started.isoformat()}" if args.after_started else (f"strictly after {after_started.isoformat()} (--after compatibility)" if args.after else "no after cutoff")
    print("Filter: " + (f"strictly before {args.before.isoformat()}" if args.before else "no before cutoff") + "; " + after_label)
    print(f"Unique root threads scanned: {len(all_roots)}")
    print(f"Workspace root candidates: {len(all_workspace_roots)}")
    if exclusion_ids:
        print(f"Workspace root candidates after explicit exclusions: {len(all_workspace_roots) - len(excluded_workspace_roots)}")
    print(f"Root threads missing cwd: {roots_without_cwd}; outside workspace: {roots_outside_workspace}")
    print(f"Matching root sessions: {len(selected)}")
    if exclusion_ids:
        print("Explicit session exclusion audit:")
        for session_id in exclusion_ids:
            subtree = exclusion_details[session_id]
            if subtree is None:
                status = "unknown ID; no matching session metadata"
            else:
                session = threads[session_id]
                started = session.started.isoformat() if session.started else "NOT AVAILABLE"
                last_event = session.last_event.isoformat() if session.last_event else "NOT AVAILABLE"
                status = f"matched; subtree contains {len(subtree)} logged session(s); started {started}; last event {last_event}"
            print(f"  {session_id}: {status}; reason: {exclusion_reasons.get(session_id, 'NOT AVAILABLE')}")
        excluded_child_ids = {
            child_id
            for root in [*selected, *selected_excluded_roots]
            for child_id in descendants(root.thread_id or "", children)[0]
            if child_id in excluded_threads
        }
        print(f"  root groups excluded from matching range: {len(selected_excluded_roots)}; child sessions removed from matching groups: {len(excluded_child_ids)}")
    print(f"Thread copies deduplicated: {errors.get('duplicate_thread_copies', 0)}")
    print(f"Sessions with conflicting metadata: {errors.get('sessions_with_metadata_conflicts', 0)}")
    print(f"Malformed JSON lines scanned: {errors.get('malformed_json_lines', 0)}")
    print(f"Logs missing a thread ID: {errors.get('logs_missing_thread_id', 0)}")
    print(f"Logs with conflicting thread IDs: {errors.get('conflicting_thread_ids', 0)}")
    print(f"Unreadable logs: {errors.get('unreadable_files', 0)}; scan errors: {errors.get('scan_errors', 0)}")
    if missing_start:
        print(f"Roots omitted by date filter because start time is unavailable: {missing_start}")
    if len(selected) < 3 and args.before:
        print("WARNING: fewer than 3 matching pre-cutoff root sessions; baseline is not padded.")

    total_threads = total_known = 0
    retry_totals = [0, 0, 0, 0, 0]
    baseline_threads: dict[str, Session] = {}
    baseline_children: dict[str, Session] = {}
    for root in selected:
        child_ids, cycle = descendants(root.thread_id or "", children)
        child_ids = [child_id for child_id in child_ids if child_id not in excluded_threads]
        included = [root] + [threads[child_id] for child_id in child_ids if child_id in threads]
        baseline_threads.update((thread.thread_id, thread) for thread in included if thread.thread_id)
        baseline_children.update((thread.thread_id, thread) for thread in included[1:] if thread.thread_id)
        report, known, count = render_session(root, included, child_ids, cycle)
        total_known += known
        total_threads += count
        for index, value in enumerate(retry_metrics(included)):
            retry_totals[index] += value
        print()
        print(report)
    print()
    print(f"Token coverage: {total_known}/{total_threads} included threads have a cumulative token total.")
    print(f"Retry-loop coverage: {retry_totals[0]} repeated role/task_name group(s), {retry_totals[1]} repeat spawn(s), {retry_totals[2]} parseable spawn calls across {retry_totals[4]} thread(s); {retry_totals[3]} spawn call(s) lacked the required role/task_name fields. Repeats use exact agent_type + task_name equality within each root session and its linked descendants.")
    print("\nBaseline token category totals (root + linked descendants):")
    print("  accounting: uncached input = input_tokens - cached_input_tokens; cached input is included in input_tokens; reasoning_output_tokens is included in output_tokens and is not additive.")
    for category in TOKEN_CATEGORIES:
        print(f"  {category}: {metric_text([thread.category_tokens.get(category) for thread in baseline_threads.values()])}")
    child_sessions = list(baseline_children.values())
    print()
    for line in role_breakdown(child_sessions):
        print(line)
    print("  largest share of known child total tokens: " + top_role(child_sessions, lambda thread: thread.tokens, "known child-token"))
    print("  largest share of known child reasoning tokens: " + top_role(child_sessions, lambda thread: thread.category_tokens.get("reasoning"), "known child reasoning-token"))

    if args.rtk_gain:
        captured_at = datetime.now(timezone.utc).isoformat()
        print()
        print(f"Supplementary global RTK command-output savings snapshot at {captured_at} (not LLM tokens; not per session):")
        try:
            result = subprocess.run(["rtk", "gain"], capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
            output = ((result.stdout or "") + (result.stderr or "")).strip()
            output = output.encode("ascii", "backslashreplace").decode("ascii")
            print(output if output else f"NOT AVAILABLE (rtk gain exited {result.returncode} with no output)")
        except OSError as error:
            print(f"NOT AVAILABLE ({type(error).__name__}: rtk command could not be started)")
    return 0


