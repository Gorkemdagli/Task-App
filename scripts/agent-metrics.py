def instant(value: str | None) -> datetime | None:
    if not isinstance(value, str):
        return None
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None
    return parsed if parsed.tzinfo is not None else None


def cutoff(value: str) -> datetime:
    parsed = instant(value)
    if parsed is None:
        raise argparse.ArgumentTypeError("use ISO 8601 date/time with an explicit timezone")
    return parsed


def exclusion_reason(value: str) -> tuple[str, str]:
    session_id, separator, reason = value.partition("=")
    if not separator or not session_id.strip() or not reason.strip():
        raise argparse.ArgumentTypeError("use SESSION_ID=REASON")
    return session_id.strip(), reason.strip()


def session_identifier(value: str) -> str:
    session_id = value.strip()
    if not session_id:
        raise argparse.ArgumentTypeError("session ID cannot be empty")
    return session_id


def matches_started(started: datetime | None, before: datetime | None, after: datetime | None) -> bool:
    if (before is not None or after is not None) and started is None:
        return False
    return (before is None or started < before) and (after is None or started > after)


def resolve_after(after: datetime | None, after_started: datetime | None) -> datetime | None:
    if after is not None and after_started is not None and after != after_started:
        raise argparse.ArgumentTypeError("--after and --after-started conflict when their timestamps differ")
    return after_started or after


